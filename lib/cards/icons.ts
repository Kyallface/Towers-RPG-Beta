const ICONS_BY_ID = new Map(PIXEL_ICONS.map((icon) => [icon.id, icon]))

export function getPixelIcon(id: string | undefined): PixelIcon | undefined {
  return id ? ICONS_BY_ID.get(id) : undefined
}

export function isPixelIconId(id: unknown): id is string {
  return typeof id === 'string' && ICONS_BY_ID.has(id)
}

/** Converts a bitmap into a single SVG path made of 1×1 squares. */
export function iconPath(pixels: readonly string[]): string {
  const segments: string[] = []
  pixels.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') segments.push(`M${x} ${y}h1v1h-1z`)
    }
  })
  return segments.join('')
}
